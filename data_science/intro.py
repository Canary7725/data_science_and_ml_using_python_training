# What is Machine Learning?

# It is a method where machine learns patterns from the data instead of being explicitly programmed.
# Major Uses:
# 1. Automation of decision
# 2. Handling of complex patterns
# 3. Improving accuracy of system over time
# 4. Used in finance, healthcare, marketing, self-driving, recommendation systems.


# Traditional Programming vs Machine Learnings
# Traditional Programming: Rules -> Output
# Machine Learning: Data -> Model -> Output

# Types of Machine Learning:
# 1. Supervised Learning
#     a. Input + Output
#     b. Predict Labels or Predict Values
#     c. Example: Linear Regression, House Price Detection, Spam Detection, Decision Tree

# 2. Unsupervised Learning
#     a. No output labels
#     b. Finds hidden patterns
#     c. Example: KNN (K neighbors classification), PCA (Principal Component Analysis), Clustering

# 3. Reinforcement Learning
#     a. Agent learns by interacting with environment
#     b. Rewards & Penalties
#     c. Used in robotics, games, navigation

